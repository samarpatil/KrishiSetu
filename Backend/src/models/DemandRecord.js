const mongoose = require("mongoose");

const demandRecordSchema = new mongoose.Schema(
  {
    productName: {
      type: String,
      required: [true, "Product name is required"],
      trim: true,
    },

    category: {
      type: String,
      required: [true, "Category is required"],
      trim: true,
    },

    quantity: {
      type: Number,
      required: [true, "Demand quantity is required"],
      min: [0, "Quantity cannot be negative"],
    },

    unit: {
      type: String,
      enum: ["kg", "quintal", "ton", "piece"],
      required: true,
    },

    location: {
      address: { type: String, trim: true, default: "" },
      lat: Number,
      lng: Number,
    },

    source: {
      type: String,
      enum: ["order", "marketplace", "manual", "external_api"],
      default: "order",
    },

    // Links demand generated by a marketplace order to that order.
    order: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Order",
      default: null,
    },

    // Cancelled orders should not contribute to forecasts.
    status: {
      type: String,
      enum: ["active", "cancelled"],
      default: "active",
    },

    recordedAt: {
      type: Date,
      default: Date.now,
    },
  },
  { timestamps: true },
);

// Prevent duplicate demand records for the same order.
demandRecordSchema.index(
  { order: 1 },
  {
    unique: true,
    partialFilterExpression: { order: { $type: "objectId" } },
  },
);

demandRecordSchema.index({ productName: 1, recordedAt: -1, status: 1 });

module.exports = mongoose.model("DemandRecord", demandRecordSchema);
